-- Performans programı: faaliyetin müdürlüğe bağlanması ve dördüncü düzey ödenek.
-- Supabase SQL editöründe çalıştırın.

alter table public.performans_programi_alt_program
  add column if not exists gerekce text,
  add column if not exists hedef text;

create table if not exists public.performans_programi_faaliyet_mudurluk (
  id bigint generated by default as identity primary key,
  faaliyet_id bigint not null references public.performans_programi_faaliyet(id) on delete cascade,
  mudurluk text not null,
  unique (faaliyet_id, mudurluk)
);

create table if not exists public.performans_programi_faaliyet_odenek (
  id bigint generated by default as identity primary key,
  faaliyet_id bigint not null references public.performans_programi_faaliyet(id) on delete cascade,
  butce_kodu_id bigint not null references public.performans_programi_butce_kodu(id) on delete restrict,
  yil integer not null check (yil >= 1900 and yil <= 2500),
  mudurluk text not null,
  tutar numeric not null default 0,
  sonraki_yil_1 numeric,
  sonraki_yil_2 numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (faaliyet_id, butce_kodu_id, yil, mudurluk)
);

alter table public.performans_programi_faaliyet_mudurluk enable row level security;
alter table public.performans_programi_faaliyet_odenek enable row level security;

drop policy if exists "pp_faaliyet_mudurluk_all" on public.performans_programi_faaliyet_mudurluk;
create policy "pp_faaliyet_mudurluk_all"
  on public.performans_programi_faaliyet_mudurluk
  for all to authenticated
  using (true)
  with check (true);

drop policy if exists "pp_faaliyet_odenek_all" on public.performans_programi_faaliyet_odenek;
create policy "pp_faaliyet_odenek_all"
  on public.performans_programi_faaliyet_odenek
  for all to authenticated
  using (true)
  with check (true);
