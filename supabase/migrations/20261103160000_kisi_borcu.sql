-- Hesaplama · kişi borcu ödeme planı

create table if not exists public.kisi_borcu_kayitlari (
  id bigint generated by default as identity primary key,
  sicil_no text not null,
  ad_soyad text not null,
  tckn text null,
  unvan text not null default '',
  faiz_turu text not null,
  ana_tutar numeric not null,
  taksit_sayisi integer not null,
  toplam_odeme numeric not null,
  belge jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid null,
  created_by_email text null,
  constraint kisi_borcu_faiz_chk check (faiz_turu in ('kanuni', 'temerrut')),
  constraint kisi_borcu_tutar_chk check (ana_tutar > 0 and taksit_sayisi > 0 and toplam_odeme > 0)
);

comment on table public.kisi_borcu_kayitlari is
  '3095 sayılı Kanun m.1 kanuni faiz ve m.2 temerrüt faizi ile kişi borcu ödeme planı.';

create index if not exists idx_kisi_borcu_created on public.kisi_borcu_kayitlari (created_at desc);

alter table public.kisi_borcu_kayitlari enable row level security;

do $$
declare
  tbl text := 'kisi_borcu_kayitlari';
  ok text := '(
        public.is_admin_like(auth.uid())
        or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
        or exists (
          select 1 from public.app_profiles ap
          where ap.id = auth.uid()
            and coalesce(ap.menu_izinleri->>''hesaplamaYonetimi'', '''') in (''true'', ''t'')
        )
      )';
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = tbl and policyname = tbl || '_select'
  ) then
    execute format('create policy %I on public.%I for select to authenticated using %s', tbl || '_select', tbl, ok);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = tbl and policyname = tbl || '_insert'
  ) then
    execute format('create policy %I on public.%I for insert to authenticated with check %s', tbl || '_insert', tbl, ok);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = tbl and policyname = tbl || '_update'
  ) then
    execute format(
      'create policy %I on public.%I for update to authenticated using %s with check %s',
      tbl || '_update', tbl, ok, ok
    );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = tbl and policyname = tbl || '_delete'
  ) then
    execute format(
      'create policy %I on public.%I for delete to authenticated using (
        public.is_admin_like(auth.uid())
        or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
      )',
      tbl || '_delete', tbl
    );
  end if;
end
$$;
