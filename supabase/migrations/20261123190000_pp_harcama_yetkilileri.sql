-- Harcama Birim Yetkilileri raporu anlık görüntüsü.
-- Kaydet / Güncelle ile doldurulur; kadro değişince Güncelle olmadan ekran değişmez.
-- Supabase SQL editöründe bir kez çalıştırın.

create table if not exists public.performans_programi_harcama_yetkilileri (
  id bigint generated by default as identity primary key,
  sira_no integer not null default 0,
  harcama_yetkilisi text not null default '',
  harcama_birimi text not null default '',
  sicil_no text not null default '',
  guncelleme_at timestamptz not null default now(),
  guncelleyen text not null default ''
);

create index if not exists pp_harcama_yetkilileri_sira_idx
  on public.performans_programi_harcama_yetkilileri (sira_no);

alter table public.performans_programi_harcama_yetkilileri enable row level security;

drop policy if exists "pp_harcama_yetkilileri_all" on public.performans_programi_harcama_yetkilileri;
create policy "pp_harcama_yetkilileri_all"
  on public.performans_programi_harcama_yetkilileri
  for all to authenticated
  using (true)
  with check (true);
