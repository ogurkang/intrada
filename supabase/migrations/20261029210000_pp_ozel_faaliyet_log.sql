-- Performans programı yılına özel faaliyet, ödeneği ve maliyet kaydı.
-- Supabase SQL editöründe çalıştırın.

create table if not exists public.performans_programi_ozel_faaliyet (
  id bigint generated by default as identity primary key,
  alt_program_id bigint not null references public.performans_programi_alt_program(id) on delete cascade,
  alt_hedef_id bigint not null references public.stratejik_plan_alt_hedef(id) on delete restrict,
  yil integer not null check (yil >= 1900 and yil <= 2500),
  sira_no integer,
  faaliyet_adi text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.performans_programi_ozel_faaliyet_butce (
  id bigint generated by default as identity primary key,
  ozel_faaliyet_id bigint not null references public.performans_programi_ozel_faaliyet(id) on delete cascade,
  butce_kodu_id bigint not null references public.performans_programi_butce_kodu(id) on delete restrict,
  yil integer not null check (yil >= 1900 and yil <= 2500),
  mudurluk text not null,
  tutar numeric not null default 0,
  sonraki_yil_butce_1 numeric,
  updated_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (ozel_faaliyet_id, butce_kodu_id, yil, mudurluk)
);

create table if not exists public.performans_programi_maliyet_log (
  id bigint generated by default as identity primary key,
  yil integer not null,
  alt_program_id bigint not null,
  alt_hedef_id bigint not null,
  faaliyet_id bigint,
  ozel_faaliyet_id bigint,
  metin text not null,
  kullanici_adi text not null,
  created_at timestamptz not null default now()
);

alter table public.performans_programi_ozel_faaliyet enable row level security;
alter table public.performans_programi_ozel_faaliyet_butce enable row level security;
alter table public.performans_programi_maliyet_log enable row level security;

drop policy if exists "pp_ozel_faaliyet_all" on public.performans_programi_ozel_faaliyet;
create policy "pp_ozel_faaliyet_all"
  on public.performans_programi_ozel_faaliyet
  for all to authenticated
  using (true)
  with check (true);

drop policy if exists "pp_ozel_faaliyet_butce_all" on public.performans_programi_ozel_faaliyet_butce;
create policy "pp_ozel_faaliyet_butce_all"
  on public.performans_programi_ozel_faaliyet_butce
  for all to authenticated
  using (true)
  with check (true);

drop policy if exists "pp_maliyet_log_all" on public.performans_programi_maliyet_log;
create policy "pp_maliyet_log_all"
  on public.performans_programi_maliyet_log
  for all to authenticated
  using (true)
  with check (true);
