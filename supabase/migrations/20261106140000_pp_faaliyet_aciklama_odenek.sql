-- Performans faaliyeti açıklaması ve dördüncü düzey ödenek teklifi.
-- Supabase SQL editöründe bir kez çalıştırın.

alter table public.performans_programi_pf_faaliyet
  add column if not exists aciklama text not null default '';

create table if not exists public.performans_programi_pf_odenek (
  id bigint generated by default as identity primary key,
  pf_faaliyet_id bigint not null references public.performans_programi_pf_faaliyet(id) on delete cascade,
  butce_kodu_id bigint not null references public.performans_programi_butce_kodu(id) on delete restrict,
  t1_butce numeric,
  t1_haziran numeric,
  t1_yil_sonu numeric,
  t_butce numeric,
  t1_tahmin numeric,
  t2_tahmin numeric,
  unique (pf_faaliyet_id, butce_kodu_id)
);

alter table public.performans_programi_pf_odenek enable row level security;

drop policy if exists "pp_pf_odenek_all" on public.performans_programi_pf_odenek;
create policy "pp_pf_odenek_all"
  on public.performans_programi_pf_odenek
  for all to authenticated
  using (true)
  with check (true);
