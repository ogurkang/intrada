-- Performans programı satır geçmişi. Supabase SQL editöründe bir kez çalıştırın.

create table if not exists public.performans_programi_satir_log (
  id bigint generated by default as identity primary key,
  tablo text not null,
  kayit_id bigint not null,
  islem text not null,
  ozet text not null default '',
  kullanici text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists performans_programi_satir_log_kayit_idx
  on public.performans_programi_satir_log (tablo, kayit_id, created_at desc);

alter table public.performans_programi_satir_log enable row level security;

drop policy if exists "pp_satir_log_all" on public.performans_programi_satir_log;
create policy "pp_satir_log_all"
  on public.performans_programi_satir_log
  for all to authenticated
  using (true)
  with check (true);
