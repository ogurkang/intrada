-- Alt programa elle eklenen faaliyet ve metinleri siler.
-- Alt program, stratejik plandaki performans hedefine bağlanır.
-- Supabase SQL editöründe çalıştırın.

delete from public.performans_programi_faaliyet;

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'performans_programi_alt_program'
      and column_name = 'gerekce'
  ) then
    update public.performans_programi_alt_program set gerekce = null, hedef = null;
  end if;
end $$;

create table if not exists public.performans_programi_alt_program_hedef (
  id bigint generated by default as identity primary key,
  alt_program_id bigint not null references public.performans_programi_alt_program(id) on delete cascade,
  alt_hedef_id bigint not null references public.stratejik_plan_alt_hedef(id) on delete restrict,
  unique (alt_program_id, alt_hedef_id)
);

alter table public.performans_programi_alt_program_hedef enable row level security;

drop policy if exists "pp_alt_program_hedef_all" on public.performans_programi_alt_program_hedef;
create policy "pp_alt_program_hedef_all"
  on public.performans_programi_alt_program_hedef
  for all to authenticated
  using (true)
  with check (true);
