-- Bir kez çalıştırın.
-- Program ve alt program durur. Onlardan sonraki performans programı kayıtları silinir.
-- Stratejik plandaki göstergeler silinir. Amaç, hedef ve performans hedefi durur.

do $$
begin
  if to_regclass('public.performans_programi_ozel_faaliyet_butce') is not null then
    delete from public.performans_programi_ozel_faaliyet_butce;
  end if;
  if to_regclass('public.performans_programi_ozel_faaliyet') is not null then
    delete from public.performans_programi_ozel_faaliyet;
  end if;
  if to_regclass('public.performans_programi_faaliyet_butce') is not null then
    delete from public.performans_programi_faaliyet_butce;
  end if;
  if to_regclass('public.performans_programi_maliyet_log') is not null then
    delete from public.performans_programi_maliyet_log;
  end if;
  if to_regclass('public.performans_programi_veri_giris') is not null then
    delete from public.performans_programi_veri_giris;
  end if;
  if to_regclass('public.performans_programi_alt_program_hedef') is not null then
    delete from public.performans_programi_alt_program_hedef;
  end if;
  if to_regclass('public.stratejik_plan_gosterge_gerceklesme') is not null then
    delete from public.stratejik_plan_gosterge_gerceklesme;
  end if;
  if to_regclass('public.stratejik_plan_gosterge') is not null then
    delete from public.stratejik_plan_gosterge;
  end if;
end $$;

alter table public.performans_programi_alt_program_hedef
  add column if not exists gerekce text not null default '';

create table if not exists public.performans_programi_pf_faaliyet (
  id bigint generated by default as identity primary key,
  bag_id bigint not null references public.performans_programi_alt_program_hedef(id) on delete cascade,
  sira_no integer not null,
  faaliyet_adi text not null,
  unique (bag_id, sira_no)
);

create table if not exists public.performans_programi_pf_gosterge (
  id bigint generated by default as identity primary key,
  faaliyet_id bigint not null references public.performans_programi_pf_faaliyet(id) on delete cascade,
  sira_no integer not null,
  gosterge_adi text not null,
  birim text not null,
  aciklama text not null default '',
  hesaplama_yontemi text not null default '',
  t2_gerceklesme numeric null,
  t1_planlanan numeric null,
  t1_yil_sonu numeric null,
  t_hedef numeric null,
  t1_tahmin numeric null,
  t2_tahmin numeric null,
  unique (faaliyet_id, sira_no)
);

alter table public.performans_programi_pf_faaliyet enable row level security;
alter table public.performans_programi_pf_gosterge enable row level security;

drop policy if exists "pp_pf_faaliyet_all" on public.performans_programi_pf_faaliyet;
create policy "pp_pf_faaliyet_all" on public.performans_programi_pf_faaliyet
  for all to authenticated using (true) with check (true);

drop policy if exists "pp_pf_gosterge_all" on public.performans_programi_pf_gosterge;
create policy "pp_pf_gosterge_all" on public.performans_programi_pf_gosterge
  for all to authenticated using (true) with check (true);
