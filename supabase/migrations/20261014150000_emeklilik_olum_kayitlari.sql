-- Hesaplama · emeklilik tazminatı ve ölüm yardımı kayıtları

create table if not exists public.emeklilik_tazminati_kayitlari (
  id bigint generated by default as identity primary key,
  sicil_no text not null,
  ad_soyad text not null,
  tckn text null,
  unvan text not null default '',
  statu text not null,
  net numeric not null,
  belge jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid null,
  created_by_email text null,
  constraint emeklilik_tazminati_statu_chk check (statu in ('Memur', 'İşçi'))
);

comment on table public.emeklilik_tazminati_kayitlari is
  '375 sayılı KHK m. 1 (D) emeklilik tazminatı. Tutarlar kaydedildiği andaki gösterge ve katsayıdandır.';

create index if not exists idx_emeklilik_tazminati_created on public.emeklilik_tazminati_kayitlari (created_at desc);

create table if not exists public.olum_yardimi_kayitlari (
  id bigint generated by default as identity primary key,
  sicil_no text not null,
  ad_soyad text not null,
  tckn text null,
  unvan text not null default '',
  toplam numeric not null,
  varis_sayisi integer not null,
  belge jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid null,
  created_by_email text null,
  constraint olum_yardimi_varis_chk check (varis_sayisi > 0)
);

comment on table public.olum_yardimi_kayitlari is
  '657 sayılı Kanun m. 208 ölüm yardımı. Tutar ve varis payları kaydedildiği andaki katsayıdandır.';

create index if not exists idx_olum_yardimi_created on public.olum_yardimi_kayitlari (created_at desc);

alter table public.emeklilik_tazminati_kayitlari enable row level security;
alter table public.olum_yardimi_kayitlari enable row level security;

do $$
declare
  tbl text;
  ok text := '(
        public.is_admin_like(auth.uid())
        or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
        or exists (
          select 1 from public.app_profiles ap
          where ap.id = auth.uid()
            and coalesce(ap.menu_izinleri->>''hesaplamaYonetimi'', '''') in (''true'', ''t'')
        )
      )';
begin
  foreach tbl in array array['emeklilik_tazminati_kayitlari', 'olum_yardimi_kayitlari']
  loop
    if not exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = tbl and policyname = tbl || '_select'
    ) then
      execute format(
        'create policy %I on public.%I for select to authenticated using %s',
        tbl || '_select', tbl, ok
      );
    end if;

    if not exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = tbl and policyname = tbl || '_insert'
    ) then
      execute format(
        'create policy %I on public.%I for insert to authenticated with check %s',
        tbl || '_insert', tbl, ok
      );
    end if;

    if not exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = tbl and policyname = tbl || '_update'
    ) then
      execute format(
        'create policy %I on public.%I for update to authenticated using %s with check %s',
        tbl || '_update', tbl, ok, ok
      );
    end if;

    if not exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = tbl and policyname = tbl || '_delete'
    ) then
      execute format(
        'create policy %I on public.%I for delete to authenticated using (
          public.is_admin_like(auth.uid())
          or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
        )',
        tbl || '_delete', tbl
      );
    end if;
  end loop;
end
$$;
