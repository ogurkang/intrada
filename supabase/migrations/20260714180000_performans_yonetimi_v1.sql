-- ─── RLS ───────────────────────────────────────────────────────────────────
alter table public.performans_donem enable row level security;
alter table public.performans_kriter enable row level security;
alter table public.performans_sms_ayar enable row level security;
alter table public.performans_degerlendirme enable row level security;
alter table public.performans_puan enable row level security;

do $$
begin
  -- donem
  if not exists (select 1 from pg_policies where tablename='performans_donem' and policyname='perf_donem_select') then
    create policy perf_donem_select on public.performans_donem for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename='performans_donem' and policyname='perf_donem_write') then
    create policy perf_donem_write on public.performans_donem for all to authenticated
      using (public.is_admin_like(auth.uid()))
      with check (public.is_admin_like(auth.uid()));
  end if;

  -- kriter
  if not exists (select 1 from pg_policies where tablename='performans_kriter' and policyname='perf_kriter_select') then
    create policy perf_kriter_select on public.performans_kriter for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename='performans_kriter' and policyname='perf_kriter_write') then
    create policy perf_kriter_write on public.performans_kriter for all to authenticated
      using (public.is_admin_like(auth.uid()))
      with check (public.is_admin_like(auth.uid()));
  end if;

  -- sms
  if not exists (select 1 from pg_policies where tablename='performans_sms_ayar' and policyname='perf_sms_select') then
    create policy perf_sms_select on public.performans_sms_ayar for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename='performans_sms_ayar' and policyname='perf_sms_write') then
    create policy perf_sms_write on public.performans_sms_ayar for all to authenticated
      using (public.is_admin_like(auth.uid()))
      with check (public.is_admin_like(auth.uid()));
  end if;

  -- değerlendirme: admin veya ilgili siciller
  if not exists (select 1 from pg_policies where tablename='performans_degerlendirme' and policyname='perf_deg_select') then
    create policy perf_deg_select on public.performans_degerlendirme for select to authenticated
    using (
      public.is_admin_like(auth.uid())
      or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
      or sicil_no in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
      or amir1_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
      or amir2_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
    );
  end if;
  if not exists (select 1 from pg_policies where tablename='performans_degerlendirme' and policyname='perf_deg_write') then
    create policy perf_deg_write on public.performans_degerlendirme for all to authenticated
    using (
      public.is_admin_like(auth.uid())
      or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
      or amir1_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
      or amir2_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
    )
    with check (
      public.is_admin_like(auth.uid())
      or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
      or amir1_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
      or amir2_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
    );
  end if;

  -- puan: değerlendirme okuyabilenler
  if not exists (select 1 from pg_policies where tablename='performans_puan' and policyname='perf_puan_select') then
    create policy perf_puan_select on public.performans_puan for select to authenticated
    using (
      exists (
        select 1 from public.performans_degerlendirme d
        where d.id = degerlendirme_id
          and (
            public.is_admin_like(auth.uid())
            or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
            or d.sicil_no in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
            or d.amir1_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
            or d.amir2_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
          )
      )
    );
  end if;
  if not exists (select 1 from pg_policies where tablename='performans_puan' and policyname='perf_puan_write') then
    create policy perf_puan_write on public.performans_puan for all to authenticated
    using (
      exists (
        select 1 from public.performans_degerlendirme d
        where d.id = degerlendirme_id
          and (
            public.is_admin_like(auth.uid())
            or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
            or d.amir1_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
            or d.amir2_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
          )
      )
    )
    with check (
      exists (
        select 1 from public.performans_degerlendirme d
        where d.id = degerlendirme_id
          and (
            public.is_admin_like(auth.uid())
            or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
            or d.amir1_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
            or d.amir2_sicil in (select ap.sicil_no from public.app_profiles ap where ap.id = auth.uid())
          )
      )
    );
  end if;
end $$;
