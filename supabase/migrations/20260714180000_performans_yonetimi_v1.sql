-- ─── Dönem (takvim yılı) ───────────────────────────────────────────────────
create table if not exists public.performans_donem (
  id bigint generated by default as identity primary key,
  yil integer not null,
  durum text not null default 'Açık'
    check (durum in ('Açık', 'Kapalı', 'Yayınlandı')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid null,
  unique (yil)
);

comment on table public.performans_donem is
  'Memur performans değerlendirme dönemi (takvim yılı).';

-- ─── Kriter tanımları ──────────────────────────────────────────────────────
create table if not exists public.performans_kriter (
  id bigint generated by default as identity primary key,
  kod integer not null,
  baslik text not null,
  aciklama text null,
  grup text not null
    check (grup in ('ortak', 'memur', 'sef', 'yonetici')),
  sira integer not null default 0,
  aktif boolean not null default true,
  unique (kod)
);

comment on table public.performans_kriter is
  'Yetkinlik bazlı performans kriterleri (ortak + role özel).';

-- ─── SMS şablonu (2. amire bildirim) ───────────────────────────────────────
create table if not exists public.performans_sms_ayar (
  id integer primary key default 1 check (id = 1),
  metin text not null default
    'Sayın {ad_soyad}, {yil} yılı performans değerlendirmelerinde 1. amir turu tamamlanmıştır. İncelemenizi bekleyen kayıtlar bulunmaktadır.',
  updated_at timestamptz not null default now()
);

insert into public.performans_sms_ayar (id) values (1)
on conflict (id) do nothing;

-- ─── Personel değerlendirme kaydı ──────────────────────────────────────────
create table if not exists public.performans_degerlendirme (
  id bigint generated by default as identity primary key,
  donem_id bigint not null references public.performans_donem(id) on delete cascade,
  sicil_no text not null,
  form_tipi text not null
    check (form_tipi in ('memur', 'sef', 'yonetici', 'baskan')),
  durum text not null default 'beklemede_1'
    check (durum in (
      'beklemede_1',
      'amir1_gonderildi',
      'iade',
      'amir2_onay',
      'tamamlandi'
    )),
  amir1_sicil text null,
  amir2_sicil text null,
  tek_amir boolean not null default false,
  puan_amir1 integer null,
  puan_amir2 integer null,
  ortalama integer null,
  iade_notu text null,
  amir1_tamam_at timestamptz null,
  amir2_onay_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (donem_id, sicil_no)
);

create index if not exists idx_perf_deg_donem on public.performans_degerlendirme (donem_id);
create index if not exists idx_perf_deg_amir1 on public.performans_degerlendirme (amir1_sicil);
create index if not exists idx_perf_deg_amir2 on public.performans_degerlendirme (amir2_sicil);
create index if not exists idx_perf_deg_sicil on public.performans_degerlendirme (sicil_no);

-- ─── Kriter puanları (1-5) ─────────────────────────────────────────────────
create table if not exists public.performans_puan (
  id bigint generated by default as identity primary key,
  degerlendirme_id bigint not null
    references public.performans_degerlendirme(id) on delete cascade,
  kriter_id bigint not null references public.performans_kriter(id),
  puan_amir1 smallint null check (puan_amir1 is null or (puan_amir1 between 1 and 5)),
  puan_amir2 smallint null check (puan_amir2 is null or (puan_amir2 between 1 and 5)),
  unique (degerlendirme_id, kriter_id)
);

create index if not exists idx_perf_puan_deg on public.performans_puan (degerlendirme_id);

