-- 4/C emekli ikramiye ve maaş (tahmini) kayıtları — Hesaplama Yönetimi

create table if not exists public.emekli_ikramiye_maas_kayitlari (
  id bigint generated by default as identity primary key,
  sicil_no text not null,
  ad_soyad text not null,
  tckn text null,
  unvan text not null default '',
  kanun text not null,
  ikramiye numeric not null,
  maas_5434 numeric null,
  belge jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid null,
  created_by_email text null,
  constraint emekli_ikramiye_maas_kanun_chk check (kanun in ('5434', '5510'))
);

comment on table public.emekli_ikramiye_maas_kayitlari is
  '4/C emekli ikramiye ve 5434 usulü maaş tahmini. Bilgi amaçlıdır; resmiyet arzetmez.';

create index if not exists idx_emekli_ikramiye_maas_created
  on public.emekli_ikramiye_maas_kayitlari (created_at desc);

alter table public.emekli_ikramiye_maas_kayitlari enable row level security;

do $$
declare
  ok text := '(
        public.is_admin_like(auth.uid())
        or not exists (select 1 from public.app_profiles ap where ap.id = auth.uid())
        or exists (
          select 1 from public.app_profiles ap
          where ap.id = auth.uid()
            and coalesce(ap.menu_izinleri->>''hesaplamaYonetimi'', '''') in (''true'', ''t'')
        )
      )';
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'emekli_ikramiye_maas_kayitlari'
      and policyname = 'emekli_ikramiye_maas_kayitlari_select'
  ) then
    execute format(
      'create policy %I on public.%I for select to authenticated using %s',
      'emekli_ikramiye_maas_kayitlari_select', 'emekli_ikramiye_maas_kayitlari', ok
    );
  end if;
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'emekli_ikramiye_maas_kayitlari'
      and policyname = 'emekli_ikramiye_maas_kayitlari_insert'
  ) then
    execute format(
      'create policy %I on public.%I for insert to authenticated with check %s',
      'emekli_ikramiye_maas_kayitlari_insert', 'emekli_ikramiye_maas_kayitlari', ok
    );
  end if;
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'emekli_ikramiye_maas_kayitlari'
      and policyname = 'emekli_ikramiye_maas_kayitlari_update'
  ) then
    execute format(
      'create policy %I on public.%I for update to authenticated using %s with check %s',
      'emekli_ikramiye_maas_kayitlari_update', 'emekli_ikramiye_maas_kayitlari', ok, ok
    );
  end if;
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'emekli_ikramiye_maas_kayitlari'
      and policyname = 'emekli_ikramiye_maas_kayitlari_delete'
  ) then
    execute format(
      'create policy %I on public.%I for delete to authenticated using %s',
      'emekli_ikramiye_maas_kayitlari_delete', 'emekli_ikramiye_maas_kayitlari', ok
    );
  end if;
end $$;
